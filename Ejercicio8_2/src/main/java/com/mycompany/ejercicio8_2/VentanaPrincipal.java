    private void calcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calcularActionPerformed
        Notas notas = new Notas();
        String nota1 = campoNota1.getText().trim();
        String nota2 = campoNota2.getText().trim();
        String nota3 = campoNota3.getText().trim();
        String nota4 = campoNota4.getText().trim();
        String nota5 = campoNota5.getText().trim();
        if (nota1.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nota 1 no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            campoNota1.requestFocus();
        }
        else if (nota2.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nota 2 no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            campoNota2.requestFocus();    
        }
        else if (nota3.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nota 3 no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            campoNota3.requestFocus();
        }
        else if (nota4.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nota 4 no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            campoNota4.requestFocus();
        }
        else if (nota5.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nota 5 no puede estar vacío.", "Error de validación", JOptionPane.WARNING_MESSAGE);
            campoNota5.requestFocus();
        }
        

            try {
                double valor1 = Double.parseDouble(nota1);
               
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese sólo un valor numérico en la nota 1", "Error de formato", JOptionPane.ERROR_MESSAGE);
                campoNota1.requestFocus();
            }
            try {
                double valor2 = Double.parseDouble(nota2);
               
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese sólo un valor numérico en la nota 2", "Error de formato", JOptionPane.ERROR_MESSAGE);
                campoNota2.requestFocus();
            }
            try {
                double valor3 = Double.parseDouble(nota3);
               
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese sólo un valor numérico en la nota 3", "Error de formato", JOptionPane.ERROR_MESSAGE);
                campoNota3.requestFocus();
            }
            try {
                double valor4 = Double.parseDouble(nota4);
               
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese sólo un valor numérico en la nota 4", "Error de formato", JOptionPane.ERROR_MESSAGE);
                campoNota4.requestFocus();
            }
            try {
                double valor5 = Double.parseDouble(nota5);
               
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor ingrese sólo un valor numérico en la nota 5", "Error de formato", JOptionPane.ERROR_MESSAGE);
                campoNota5.requestFocus();
            }
         

        

        notas.listaNotas[0] = Double.parseDouble(campoNota1.getText());
        notas.listaNotas[1] = Double.parseDouble(campoNota2.getText());
        notas.listaNotas[2] = Double.parseDouble(campoNota3.getText());
        notas.listaNotas[3] = Double.parseDouble(campoNota4.getText());
        notas.listaNotas[4] = Double.parseDouble(campoNota5.getText());
        notas.calcularPromedio();
        notas.calcularDesviación();
        promedio.setText("Promedio = " + String.valueOf(String.format("%.2f",notas.calcularPromedio())));
        double desv = notas.calcularDesviación();
        desviación.setText("Desviación estándar = " + String.valueOf(String.format("%.2f",desv)));
        mayor.setText("Valor mayor = " + String.valueOf(String.format("%.2f",notas.calcularMayor())));
        menor.setText("Valor menor = " + String.valueOf(String.format("%.2f",notas.calcularMenor())));
    }//GEN-LAST:event_calcularActionPerformed

